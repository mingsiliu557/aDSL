#!/usr/bin/env python3
"""Build deterministic calibration controls for final standing stability."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import trimesh


@dataclass(frozen=True)
class Primitive:
    kind: str
    xyz: tuple[float, float, float]
    size: tuple[float, ...]


CONTROLS = {
    "CTRL_STABLE_WIDE_BOX": [
        Primitive("box", (0.0, 0.0, 0.20), (1.2, 1.0, 0.4)),
    ],
    "CTRL_STABLE_LOW_CYLINDER": [
        Primitive("cylinder", (0.0, 0.0, 0.20), (0.55, 0.4)),
    ],
    "CTRL_UNSTABLE_OVERHANG": [
        Primitive("box", (0.0, 0.0, 0.05), (0.20, 0.20, 0.10)),
        Primitive("box", (0.18, 0.0, 0.60), (0.06, 0.06, 1.10)),
        Primitive("sphere", (0.48, 0.0, 1.25), (0.34,)),
    ],
    "CTRL_UNSTABLE_TOP_HEAVY": [
        Primitive("cylinder", (0.0, 0.0, 0.04), (0.06, 0.08)),
        Primitive("cylinder", (0.08, 0.0, 0.64), (0.04, 1.20)),
        Primitive("sphere", (0.18, 0.0, 1.35), (0.38,)),
    ],
    "CTRL_UNSTABLE_LINE_SUPPORT": [
        Primitive("sphere", (-0.22, 0.0, 0.06), (0.06,)),
        Primitive("sphere", (0.22, 0.0, 0.06), (0.06,)),
        Primitive("box", (0.0, 0.0, 0.16), (0.50, 0.05, 0.12)),
        Primitive("cylinder", (0.0, 0.08, 0.75), (0.04, 1.18)),
        Primitive("box", (0.0, 0.28, 1.38), (0.55, 0.45, 0.30)),
    ],
}


def geometry_xml(index: int, primitive: Primitive) -> str:
    x, y, z = primitive.xyz
    if primitive.kind == "box":
        sx, sy, sz = primitive.size
        geometry = f'<box size="{sx} {sy} {sz}"/>'
    elif primitive.kind == "cylinder":
        radius, length = primitive.size
        geometry = f'<cylinder radius="{radius}" length="{length}"/>'
    elif primitive.kind == "sphere":
        (radius,) = primitive.size
        geometry = f'<sphere radius="{radius}"/>'
    else:
        raise ValueError(primitive.kind)
    return (
        f'    <collision name="collision_{index}">\n'
        f'      <origin xyz="{x} {y} {z}" rpy="0 0 0"/>\n'
        f'      <geometry>{geometry}</geometry>\n'
        f'    </collision>'
    )


def mesh_for(primitive: Primitive) -> trimesh.Trimesh:
    if primitive.kind == "box":
        mesh = trimesh.creation.box(extents=primitive.size)
    elif primitive.kind == "cylinder":
        radius, length = primitive.size
        mesh = trimesh.creation.cylinder(radius=radius, height=length, sections=64)
    else:
        mesh = trimesh.creation.icosphere(subdivisions=3, radius=primitive.size[0])
    transform = np.eye(4)
    transform[:3, 3] = primitive.xyz
    mesh.apply_transform(transform)
    return mesh


def write_control(root: Path, name: str, primitives: list[Primitive]) -> None:
    case_dir = root / name
    case_dir.mkdir(parents=True, exist_ok=True)
    collisions = "\n".join(
        geometry_xml(index, primitive) for index, primitive in enumerate(primitives)
    )
    urdf = (
        f'<robot name="{name}">\n'
        f'  <link name="assembly">\n{collisions}\n  </link>\n'
        f'</robot>\n'
    )
    (case_dir / "scene.urdf").write_text(urdf, encoding="utf-8")
    trimesh.Scene(
        {f"primitive_{i}": mesh_for(p) for i, p in enumerate(primitives)}
    ).export(case_dir / "scene.glb")
    source = (
        '"""Deterministic calibration control; generated by build_controls.py."""\n\n'
        f"CONTROL_NAME = {name!r}\n"
        f"PRIMITIVES = {primitives!r}\n"
    )
    (case_dir / "source.py").write_text(source, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-root", type=Path, required=True)
    args = parser.parse_args()
    for name, primitives in CONTROLS.items():
        write_control(args.output_root.resolve(), name, primitives)
    print(f"Wrote {len(CONTROLS)} controls to {args.output_root.resolve()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
